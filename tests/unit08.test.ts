import assert from "node:assert/strict";
import { MemoryAdapter } from "../src/platform/memory-adapter.ts";
import { sniffMediaType } from "../src/platform/bytes.ts";
import { readFileSync } from "node:fs";
const code = (name: string) => (e: unknown) => { assert.equal((e as {code: string}).code, name); return true; };
const api = new MemoryAdapter();
const id = (await api.createDraft({body: "合成编辑器正文", eventDate: "2026-11-11"})).row.recordId;
const tag = await api.createTag("编辑器新标签");
await api.setRecordTags(id, [tag.tagId], 0);
await assert.rejects(api.setRecordTags(id, [], 0), code("META_REVISION_CONFLICT"));
await assert.rejects(api.createTag("编辑器新标签"), code("TAG_NAME_CONFLICT"));
await assert.rejects(api.setFavorite(id, true, 0), code("RECORD_NOT_FORMAL"));
await api.setRecordTags(id, [], 1);
await api.setRecordTags(id, [tag.tagId], 2);
await api.commitRecord(id, 0);
assert.deepEqual((await api.getRecord(id)).tagIds, [tag.tagId]);
const formal = (await api.getRecord(id)).formal;
await api.createDraft({baseRecordId: id});
await api.saveDraft({recordId: id, body: "独立草稿正文"});
await api.setRecordTags(id, [], 3);
assert.deepEqual((await api.getRecord(id)).formal, formal);
assert.equal((await api.getRecord(id)).draft?.body, "独立草稿正文");
const discarded = (await api.createDraft({body: "未发布"})).row.recordId;
await api.setRecordTags(discarded, [tag.tagId], 0);
await api.discardDraft(discarded);
await assert.rejects(api.getRecord(discarded));
const heic = Uint8Array.from([0,0,0,24, ...Buffer.from("ftypheic"),0,0,0,0, ...Buffer.from("mif1heic")]);
assert.equal(sniffMediaType("unknown.bin", heic), "image/heic");
const photo = (await api.attachPhotoBytes({recordId: id, fileName:"synthetic.bin", bytes: heic, caption:"合成 HEIC"})).row.draft!.photos[0]!;
await assert.rejects(api.photoThumbUrl(photo.assetId), code("HEIC_UNSUPPORTED"));
const ui = readFileSync(new URL("../src/ui/main.ts", import.meta.url), "utf8");
assert.match(ui.slice(ui.indexOf("async function loadCoverImage"), ui.indexOf("function timelineCover")), /photoThumbUrl/);
assert.doesNotMatch(ui.slice(ui.indexOf("async function loadCoverImage"), ui.indexOf("function timelineCover")), /photoDataUrl/);
